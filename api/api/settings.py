# https://docs.djangoproject.com/en/6.1/ref/settings/#databases
def _build_mssql_options(dsn_env_var):
    options = {
        "driver": os.getenv("DRIVERODBC", "ODBC Driver 17 for SQL Server"),
        "host_is_server": True,
        "autocommit": True,
        "unicode_results": True,
        "isolation_level": "READ UNCOMMITTED",
        "connection_timeout": DATABASE_CONNECTION_TIMEOUT,
        "query_timeout": DATABASE_QUERY_TIMEOUT,
        "extra_params": "MARS_Connection=Yes",
    }

    dsn = (os.getenv(dsn_env_var, "") or "").strip()
    if dsn:
        options["dsn"] = dsn

    return options

